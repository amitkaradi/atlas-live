class QuantumPriceModel:
    """Spinor wave-packet of the log-return, evolved by split-step Fourier.

    State layout
    ------------
    pure  : psi, shape (2, N)       - component 0 = bull, 1 = bear
    mixed : rho, shape (2N, 2N)     - density matrix, index = s * N + i
    """

    def __init__(self, params: QPMParams, S0: float = 100.0, L: float = 1.5, N: int = 512):
        self.p = params
        self.S0 = float(S0)
        self.N = int(N)
        self.L = float(L)
        self.x = np.linspace(-L, L, N, endpoint=False)
        self.dx = self.x[1] - self.x[0]
        self.k = 2.0 * np.pi * np.fft.fftfreq(N, d=self.dx)
        self.V = params.potential(self.x)
        self.t = 0.0
        self.psi: np.ndarray | None = None
        self.rho: np.ndarray | None = None
        self.history: list[tuple[float, np.ndarray]] = []
        self.reset()

    # ----- state preparation -------------------------------------------------
    def reset(self) -> None:
        p = self.p
        packet = (2 * np.pi * p.sigma0**2) ** -0.25 * np.exp(-self.x**2 / (4 * p.sigma0**2)) * np.exp(1j * p.k0 * self.x)
        spin = np.array([np.sqrt(p.p_bull), np.sqrt(1.0 - p.p_bull)], dtype=complex)
        psi = spin[:, None] * packet[None, :]
        psi /= np.sqrt(self._norm_pure(psi))
        self.t = 0.0
        self.history = []
        if p.gamma > 0:
            flat = psi.reshape(-1)
            self.rho = np.outer(flat, flat.conj())
            self.psi = None
        else:
            self.psi = psi
            self.rho = None
        self.history.append((0.0, self.density()))

    def _norm_pure(self, psi: np.ndarray) -> float:
        return float(np.sum(np.abs(psi) ** 2) * self.dx)

    # ----- propagators ---------------------------------------------------------
    def _apply_U(self, a: np.ndarray, dt: float) -> np.ndarray:
        """Apply exp(-z H dt) (Strang split) to an array of shape (2, N, ...)."""
        p = self.p
        z = p.z
        half = 0.5 * dt
        # potential + spinor part: H_pot = V(x) I + b(x) sigma_z + c sigma_x
        a = self._apply_spinor_potential(a, z * half)
        # kinetic + drift in momentum space: exp(-z sigma^2 k^2 dt) exp(-i k mu dt).
        # In the comoving frame the drift is applied to the density at read-out instead,
        # so the potential (magnet, levels, anchor) rides along with the fair value.
        if p.comoving:
            drift = 0.0
        else:  # drift + decaying momentum, integrated over this step
            drift = self._displacement(self.t + dt) - self._displacement(self.t)
        kin = np.exp(-z * p.sigma**2 * self.k**2 * dt - 1j * self.k * drift)
        shape = (1, self.N) + (1,) * (a.ndim - 2)
        a = np.fft.ifft(np.fft.fft(a, axis=1) * kin.reshape(shape), axis=1)
        a = self._apply_spinor_potential(a, z * half)
        return a

    def _apply_spinor_potential(self, a: np.ndarray, zt: complex) -> np.ndarray:
        """exp(-zt (V I + b sigma_z + c sigma_x)) at every grid point, vectorised.

        exp(-zt(bσz+cσx)) = cosh(zt w) I - sinh(zt w)/w (bσz + cσx),  w = sqrt(b^2+c^2)."""
        p = self.p
        b = -p.g * self.x  # bull lowers energy for higher x, bear raises it
        c = p.omega
        w = np.sqrt(b**2 + c**2)
        ch = np.cosh(zt * w)
        with np.errstate(divide="ignore", invalid="ignore"):
            shw = np.where(w > 0, np.sinh(zt * w) / np.where(w > 0, w, 1.0), zt)
        pref = np.exp(-zt * self.V)
        shape = (self.N,) + (1,) * (a.ndim - 2)
        ch, shw, pref, b = (q.reshape(shape) for q in (ch, shw, pref, np.broadcast_to(b, self.N)))
        up, dn = a[0], a[1]
        new_up = ch * up - shw * (b * up + c * dn)
        new_dn = ch * dn - shw * (-b * dn + c * up)
        return pref * np.stack([new_up, new_dn], axis=0)

    def step(self, dt: float) -> None:
        p = self.p
        if self.psi is not None:
            psi = self._apply_U(self.psi, dt)
            if p.theta < 1.0:  # non-unitary branch: renormalise (Feynman-Kac weight)
                psi /= np.sqrt(self._norm_pure(psi))
            self.psi = psi
        else:
            rho = self.rho.reshape(2, self.N, 2 * self.N)
            rho = self._apply_U(rho, dt).reshape(2 * self.N, 2 * self.N)  # U rho
            rho = rho.conj().T.reshape(2, self.N, 2 * self.N)
            rho = self._apply_U(rho, dt).reshape(2 * self.N, 2 * self.N)  # U (U rho)^† = U rho U†
            # Lindblad dephasing in the position basis, L = x:
            # rho(x, x') -> rho(x, x') exp(-gamma (x - x')^2 dt / 2)
            xx = np.tile(self.x, 2)
            deph = np.exp(-0.5 * p.gamma * (xx[:, None] - xx[None, :]) ** 2 * dt)
            rho = rho * deph
            rho /= np.trace(rho).real * self.dx
            self.rho = rho
        self.t += dt

    def evolve(self, T: float, n_steps: int = 200, record_every: int = 1) -> "QuantumPriceModel":
        dt = T / n_steps
        for i in range(1, n_steps + 1):
            self.step(dt)
            if i % record_every == 0 or i == n_steps:
                self.history.append((self.t, self.density()))
        return self

    # ----- measurement ("collapse" on a trade) --------------------------------
    def measure(self, rng: np.random.Generator | None = None, sigma_post: float | None = None) -> float:
        """A trade is a measurement: sample x from |psi|^2, collapse the packet
        onto a narrow Gaussian around it (width sigma_post) and continue.
        Returns the realised log-return."""
        rng = rng or np.random.default_rng()
        pdf = self.density()
        x_obs = rng.choice(self.x, p=pdf / pdf.sum())
        s = sigma_post or self.p.sigma0
        x_frame = x_obs - self._shift()  # project in the frame the state lives in
        proj = np.exp(-((self.x - x_frame) ** 2) / (4 * s**2))
        if self.psi is not None:
            self.psi = self.psi * proj[None, :]
            self.psi /= np.sqrt(self._norm_pure(self.psi))
        else:
            P = np.tile(proj, 2)
            self.rho = self.rho * np.outer(P, P)
            self.rho /= np.trace(self.rho).real * self.dx
        return float(x_obs)

    # ----- observables ---------------------------------------------------------
    def _displacement(self, t: float) -> float:
        """Classical displacement by time t: drift mu plus the decaying momentum drift.

        The phase momentum k0 is a genuine quantum feature, but for theta < 1 the
        diffusive part of the evolution erases it within tau = sigma0^2 / ((1-theta) sigma^2),
        which is a tiny fraction of any horizon.  So persistence of a trend is modelled
        explicitly: v(t) = v_mom exp(-t / tau_mom)."""
        p = self.p
        mom = p.v_mom * p.tau_mom * (1.0 - np.exp(-t / p.tau_mom)) if p.v_mom else 0.0
        return p.mu * t + mom

    def _shift(self) -> float:
        """Lab-frame displacement of the comoving frame at the current time."""
        return self._displacement(self.t) if self.p.comoving else 0.0

    def density(self) -> np.ndarray:
        """p(x) = sum_s |psi_s(x)|^2  (or diagonal of rho), normalised to 1 in dx,
        on the lab-frame grid self.x (shifted by mu t in the comoving frame)."""
        if self.psi is not None:
            d = np.sum(np.abs(self.psi) ** 2, axis=0)
        else:
            d = np.diag(self.rho).real.reshape(2, self.N).sum(axis=0)
        d = d / (d.sum() * self.dx)
        s = self._shift()
        if s:
            d = np.interp(self.x - s, self.x, d, left=0.0, right=0.0)
            d = d / max(d.sum() * self.dx, 1e-300)
        return d

    def prob_bull(self) -> float:
        if self.psi is not None:
            return float(np.sum(np.abs(self.psi[0]) ** 2) * self.dx)
        return float(np.diag(self.rho).real[: self.N].sum() * self.dx)

    def momentum_density(self) -> tuple[np.ndarray, np.ndarray]:
        """|psi_hat(k)|^2 - the distribution of 'trend'."""
        if self.psi is not None:
            ph = np.fft.fft(self.psi, axis=1)
            d = np.sum(np.abs(ph) ** 2, axis=0)
        else:
            rho = self.rho.reshape(2, self.N, 2, self.N)
            d = np.zeros(self.N)
            for s in range(2):
                rk = np.fft.fft(np.fft.ifft(rho[s, :, s, :], axis=0), axis=1)
                d += np.diag(rk).real
        order = np.argsort(self.k)
        k = self.k[order]
        d = d[order]
        return k, d / (d.sum() * (k[1] - k[0]))

    def uncertainty(self) -> tuple[float, float, float]:
        """(Delta x, Delta k, product).  The product is bounded below by 1/2."""
        px = self.density()
        mx = np.sum(self.x * px) * self.dx
        dx = np.sqrt(np.sum((self.x - mx) ** 2 * px) * self.dx)
        k, pk = self.momentum_density()
        dk_ = k[1] - k[0]
        mk = np.sum(k * pk) * dk_
        dk = np.sqrt(np.sum((k - mk) ** 2 * pk) * dk_)
        return float(dx), float(dk), float(dx * dk)

    def forecast(self, r: float = 0.0, T: float | None = None, strikes: Sequence[float] = ()) -> dict:
        """Everything a trader wants out of |psi|^2 at the current time."""
        p = self.density()
        x, dx = self.x, self.dx
        cdf = np.cumsum(p) * dx - 0.5 * p * dx  # midpoint rule: a grid point's own bin is split half below, half above
        S = self.S0 * np.exp(x)
        mean_x = np.sum(x * p) * dx
        var_x = np.sum((x - mean_x) ** 2 * p) * dx
        std_x = np.sqrt(var_x)
        skew = np.sum(((x - mean_x) / std_x) ** 3 * p) * dx
        kurt = np.sum(((x - mean_x) / std_x) ** 4 * p) * dx

        def q(a: float) -> float:
            return float(np.interp(a, cdf, x))

        T = self.t if T is None else T
        disc = np.exp(-r * T)
        out = {
            "t": self.t,
            "E[S]": float(np.sum(S * p) * dx),
            "median_S": float(self.S0 * np.exp(q(0.5))),
            "mean_logret": float(mean_x),
            "std_logret": float(std_x),
            "skew": float(skew),
            "kurtosis": float(kurt),
            "VaR_95": float(self.S0 * (1 - np.exp(q(0.05)))),
            "VaR_99": float(self.S0 * (1 - np.exp(q(0.01)))),
            "quantiles_S": {a: float(self.S0 * np.exp(q(a))) for a in (0.01, 0.05, 0.25, 0.5, 0.75, 0.95, 0.99)},
            "P(S_T > S0)": float(1.0 - np.interp(0.0, x, cdf)),
            "P(bull)": self.prob_bull(),
            "calls": {},
            "puts": {},
        }
        for K in strikes:
            out["calls"][K] = float(disc * np.sum(np.maximum(S - K, 0) * p) * dx)
            out["puts"][K] = float(disc * np.sum(np.maximum(K - S, 0) * p) * dx)
        return out

    def log_likelihood(self, realised_x: Sequence[float]) -> float:
        """Sum of log p(x_i) for realised log-returns at the current horizon."""
        p = np.maximum(self.density(), 1e-300)
        return float(np.sum(np.log(np.interp(realised_x, self.x, p, left=1e-300, right=1e-300))))


class QPMEnsemble:
    """A mixed state over the particle's mass: rho = sum_k w_k |psi_k><psi_k|
    with sigma_k^2 = sigma^2 * m_k, (m_k, w_k) from `mass_mixture_nodes(nu)`.

    Economically: the volatility itself is uncertain.  A Gaussian scale-mixed
    with nu/chi2_nu is a Student-t, so this gives the wave packet power-law-like
    tails while keeping every other feature (magnet, levels, momentum, sentiment).
    Exposes the same read-out API as QuantumPriceModel (x, dx, density, forecast,
    log_likelihood, prob_bull)."""

    def __init__(self, params: QPMParams, S0: float = 100.0, L: float = 1.5, N: int = 512):
        self.p = params
        self.S0 = float(S0)
        m, w = mass_mixture_nodes(params.nu, params.n_mix)
        self.weights = w
        self.members = []
        for mk in m:
            q = replace(params, sigma=params.sigma * float(np.sqrt(mk)), nu=np.inf)
            if params.k0:  # keep the intended group velocity v = 2 sigma^2 k0 for every member
                q.k0 = params.k0 * params.sigma**2 / q.sigma**2
            self.members.append(QuantumPriceModel(q, S0=S0, L=L, N=N))
        self.p = params
        self.x, self.dx, self.N = self.members[0].x, self.members[0].dx, self.members[0].N
        self.t = 0.0

    def evolve(self, T: float, n_steps: int = 200, record_every: int = 1) -> "QPMEnsemble":
        for m in self.members:
            m.evolve(T, n_steps=n_steps, record_every=record_every)
        self.t = self.members[0].t
        return self

    def density(self) -> np.ndarray:
        d = sum(w * m.density() for w, m in zip(self.weights, self.members))
        return d / (d.sum() * self.dx)

    def prob_bull(self) -> float:
        return float(sum(w * m.prob_bull() for w, m in zip(self.weights, self.members)))

    def forecast(self, r: float = 0.0, T: float | None = None, strikes: Sequence[float] = ()) -> dict:
        return QuantumPriceModel.forecast(self, r=r, T=T, strikes=strikes)  # only uses density/x/dx/S0/t/prob_bull

    def log_likelihood(self, realised_x: Sequence[float]) -> float:
        return QuantumPriceModel.log_likelihood(self, realised_x)


def build_model(params: QPMParams, S0: float = 100.0, L: float = 1.5, N: int = 512):
    """QuantumPriceModel for a pure state, QPMEnsemble when params.nu is finite."""
    if np.isfinite(params.nu) and params.n_mix > 1:
        return QPMEnsemble(params, S0=S0, L=L, N=N)
    return QuantumPriceModel(params, S0=S0, L=L, N=N)


