"""
QPM - Quantum Price Model
=========================

A conceptual model that describes the *future* price of a stock as a quantum
state instead of a single number.  The log-return x = ln(S/S0) plays the role
of "position".  The future is a superposition over all possible returns,

    |psi(t)> = sum_k c_k(t) |x_k>,      P(x_k) = |c_k|^2      (Born rule)

and it evolves under a market Hamiltonian

    H = -sigma^2 d^2/dx^2  +  V(x)  +  g * sigma_z (x)  +  Omega * sigma_x
        ^ "kinetic" term       ^ market forces   ^ sentiment-price coupling

The state is a two-component spinor (bull / bear sentiment qubit) over the
price grid.  Evolution is generated by

    d psi / dt = -(1 - theta + i theta) H psi

so that  theta = 0  is pure diffusion (the Black-Scholes heat kernel in
imaginary time) and  theta = 1  is a unitary Schrodinger evolution with
interference.  Decoherence (information flow / liquidity) is a Lindblad
dephasing in the position basis with rate gamma.

Nothing here is physics.  hbar, "mass" and "energy" are modelling devices.
This is not investment advice.
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace
from typing import Callable, Sequence

import numpy as np

# ----------------------------------------------------------------------------
# Market potential V(x): where the economic forces live
# ----------------------------------------------------------------------------


@dataclass
class Potential:
    """V(x) built from interpretable economic pieces (all in log-return units).

    lam, x_f     : harmonic well  lam * (x - x_f)^2  -> mean reversion toward the
                   fundamental log-level x_f (0 = today's price).
    levels       : list of (x_j, h_j, w_j).  Smoothed delta barriers
                   h_j * exp(-(x-x_j)^2 / 2 w_j^2).  h_j > 0 is resistance /
                   support (the packet is repelled), h_j < 0 is a "magnet"
                   (a price the market likes to sit at).
    quartic      : (a, b) -> a x^4 - b x^2, a double well with minima at
                   +-sqrt(b / 2a): two regimes (good report / bad report).
    magnet_depth,
    magnet_width : attractive well  -magnet_depth * exp(-(x-x_f)^2 / 2 w^2)
                   at the fundamental level.  Its bound state is ~ exp(-kappa|x|)
                   (a Laplace density), i.e. a principled source of fat tails.

    Energy scale: the natural unit is 1/T (per year).  A feature only matters
    over horizon T if V * T is O(1), e.g. barriers of height ~10-50 and
    mean-reversion lam ~ 500-2000 for a 30-day horizon.
    """

    lam: float = 0.0
    x_f: float = 0.0
    levels: list[tuple[float, float, float]] = field(default_factory=list)
    level_scale: float = 1.0  # multiplies every level height (one fittable knob for all barriers)
    quartic: tuple[float, float] = (0.0, 0.0)
    magnet_depth: float = 0.0
    magnet_width: float = 0.05
    magnet_x: float = 0.0  # centre of the magnet (today's price in the drifting frame)

    def __call__(self, x: np.ndarray) -> np.ndarray:
        v = self.lam * (x - self.x_f) ** 2
        a, b = self.quartic
        if a or b:
            v = v + a * x**4 - b * x**2
        if self.magnet_depth:
            v = v - self.magnet_depth * np.exp(-0.5 * ((x - self.magnet_x) / self.magnet_width) ** 2)
        for xj, hj, wj in self.levels:
            v = v + self.level_scale * hj * np.exp(-0.5 * ((x - xj) / wj) ** 2)
        return v

    @staticmethod
    def double_well(depth: float, x_min: float) -> tuple[float, float]:
        """(a, b) for a x^4 - b x^2 with minima at +-x_min and well depth `depth`."""
        if depth <= 0 or x_min <= 0:
            return (0.0, 0.0)
        a = depth / x_min**4
        return (a, 2.0 * a * x_min**2)


