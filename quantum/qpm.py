@dataclass
class QPMParams:
    """All parameters are per year; x is a log-return."""

    sigma: float = 0.25  # annualised volatility.  "mass" m = 1 / sigma^2
    mu: float = 0.0  # structural drift (r, risk premium) -> translation
    sigma0: float = 0.02  # initial packet width (immediate uncertainty)
    k0: float = 0.0  # initial momentum (phase gradient).  k0 = v / (2 sigma^2)
    theta: float = 1.0  # 0 = Black-Scholes diffusion, 1 = unitary quantum
    gamma: float = 0.0  # decoherence rate (position dephasing), ~ liquidity
    g: float = 0.0  # coupling sentiment <-> price
    omega: float = 0.0  # sentiment flip rate (bull <-> bear)
    p_bull: float = 0.5  # initial probability of the bull regime
    potential: Potential = field(default_factory=Potential)
    # --- added for the v2 backtest -------------------------------------------
    v_mom: float = 0.0  # momentum: an extra drift (per year) that decays with time constant tau_mom
    tau_mom: float = 20.0 / 252.0  # momentum half-life scale (years).  Displacement = v_mom * tau * (1 - exp(-t/tau))
    comoving: bool = True  # potential rides along with the drift mu (fixes the bearish median of v1)
    nu: float = np.inf  # mixed state over the "mass": sigma^2 ~ sigma^2 * nu / chi2_nu.  inf = pure state
    n_mix: int = 7  # quadrature nodes for the mass mixture

    @property
    def z(self) -> complex:
        """Complex 'time direction': (1 - theta) real + i theta imaginary."""
        return complex(1.0 - self.theta, self.theta)


def effective_variance_factor(theta: float) -> float:
    """Variance of |psi|^2 for a free packet (sigma0 -> 0) is
    f(theta) * sigma^2 * t  with  f = (1 - theta) + theta^2 / (1 - theta).
    f(0) = 1 (Black-Scholes), f(0.5) = 1, f -> inf as theta -> 1 (ballistic).
    Use it to rescale sigma so that the model variance matches the market's."""
    if theta >= 1.0:
        return np.inf
    return (1.0 - theta) + theta**2 / (1.0 - theta)


def momentum_from_returns(log_returns: Sequence[float], sigma: float, dt_days: float = 1.0) -> float:
    """Turn recent realised log-returns into an initial phase gradient k0.

    Group velocity of the packet under H = sigma^2 k^2 is v = 2 sigma^2 k,
    so a trend v (per year) corresponds to k0 = v / (2 sigma^2)."""
    r = np.asarray(log_returns, dtype=float)
    v = r.mean() * (252.0 / dt_days)  # annualised trend
    return float(v / (2.0 * sigma**2))


def mass_mixture_nodes(nu: float, K: int = 7) -> tuple[np.ndarray, np.ndarray]:
    """Variance multipliers m_k and weights w_k for sigma^2 -> sigma^2 * m,
    m = nu / W, W ~ chi2_nu (the scale mixture that turns a Gaussian into a
    Student-t with nu degrees of freedom).  Nodes sit at fixed quantiles so the
    outermost one reaches well into the tail; weights are the quantile cells."""
    from scipy import stats

    if K == 1 or not np.isfinite(nu):
        return np.ones(1), np.ones(1)
    edges = np.linspace(0, 1, K + 1)
    edges = 0.5 * (1 - np.cos(np.pi * edges))  # denser cells in the tails
    mids = 0.5 * (edges[1:] + edges[:-1])
    w = np.diff(edges)
    m = nu / stats.chi2.ppf(1 - mids, nu)
    m = m / np.sum(w * m)  # unit mean variance multiplier -> sigma keeps its meaning
    return m, w / w.sum()


