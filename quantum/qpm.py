def black_scholes_density(x: np.ndarray, T: float, sigma: float, mu: float = 0.0, sigma0: float = 0.0) -> np.ndarray:
    """Lognormal (Gaussian in x) with mean mu T and variance sigma^2 T + sigma0^2."""
    var = sigma**2 * T + sigma0**2
    return np.exp(-((x - mu * T) ** 2) / (2 * var)) / np.sqrt(2 * np.pi * var)


